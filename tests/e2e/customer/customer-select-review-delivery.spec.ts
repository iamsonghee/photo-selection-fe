  await expect(page.getByText("아직 선택한 사진이 없어요.")).toBeVisible();
  await expect(page.getByRole("button", { name: "결과 만들기", exact: true })).toHaveCount(0);
  await page.getByRole("link", { name: "사진 고르기", exact: true }).click();
  await page.getByRole("button", { name: "ACUT_1_0004.jpg 크게 보기", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "ACUT_1_0004.jpg 최종 선택", exact: true }).click();
  await page.getByRole("button", { name: "상세보기 닫기" }).click();
  await page.getByRole("link", { name: /최종 검토/ }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.getByRole("heading", { level: 1, name: "최종 검토" })).toBeVisible();
  await expect.poll(() => page.getByRole("button", { name: "ACUT_1_0004.jpg 크게 보기", exact: true }).locator("img").evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
